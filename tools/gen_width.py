#!/usr/bin/env python3
"""Writes src/width_tables.mettle from Python's Unicode database.

Width rules (UAX #11 East Asian Width, with the usual terminal choices that
glibc wcwidth, termbox2 and notcurses make):
  0  nonspacing and enclosing marks (Mn, Me), format characters (Cf) except
     U+00AD, Hangul medial and final jamo, and emoji skin tone modifiers.
  2  East_Asian_Width W or F, and the unassigned parts of planes 2 and 3.
  1  everything else that prints.
Run: python3 tools/gen_width.py > src/width_tables.mettle
"""
import sys, unicodedata

def zero(cp):
    if cp == 0xAD: return False
    if 0x1160 <= cp <= 0x11FF or 0xD7B0 <= cp <= 0xD7FF: return True
    if 0x1F3FB <= cp <= 0x1F3FF: return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")

def wide(cp):
    if 0x20000 <= cp <= 0x2FFFD or 0x30000 <= cp <= 0x3FFFD: return True
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F")

def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(cp)
        if ok and start is None: start = cp
        if not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return out

def emit(name, rs):
    flat = []
    for a, b in rs: flat += [a, b]
    print(f"export const {name}_N = {len(rs)};")
    print(f"export const {name}: uint32[{len(flat)}] = [")
    for i in range(0, len(flat), 8):
        print("  " + ", ".join(f"0x{v:X}" for v in flat[i:i+8]) + ",")
    print("];\n")

print("// Generated by tools/gen_width.py from the Unicode database, version "
      + unicodedata.unidata_version + ". Do not edit.")
print("// Pairs of [first, last] code points, sorted.\n")
emit("TUI_ZERO_W", ranges(zero))
emit("TUI_WIDE_W", ranges(lambda c: wide(c) and not zero(c)))
